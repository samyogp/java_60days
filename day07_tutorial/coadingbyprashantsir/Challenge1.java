package day07_tutorial.coadingbyprashantsir;

public class Challenge1 {
    // perfect example of escape sequence in java to go next line and print the pattern of stars in the output.

    public static void main(String[] args) {
        // Right half Pyramid.
        System.out.println("*\n**\n***\n****\n*****");



        // reverse right half pyramid of stars in the output.
        System.out.println("*****\n****\n***\n**\n*");

        // Left Half Pyramid.
        System.out.println("    *\n   **\n  ***\n ****\n*****");



    }
    
}
