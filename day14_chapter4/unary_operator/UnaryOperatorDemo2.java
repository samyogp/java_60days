package day14_chapter4.unary_operator;

public class UnaryOperatorDemo2 {
    // converts positive value into negative value.
    public static void main(String[] args) {
        // positive value is converted into negative value by using unary minus operator (-)

        int a = 5;
        System.out.println(a);
        System.out.println(-a);
       
        // negative value converted into positive value by using unary minus operator (-)
        
        int b = -12;
        System.out.println(b);
        System.out.println(-b);

    }
    
}
