package day14_chapter4.Third_challenge;

public class BitwiseComplement {
    public static void main(String[] args) {
        // create a program that shows bitwise complement of a number.
        int number = 5; // Example number
        int complement = ~number; // Perform bitwise complement operation
        System.out.println("The bitwise complement of " + number + " is: " + complement);
    }
    
}
