package day14_chapter4.arithmetic_operator;

public class OrderOfOperationDemo {
public static void main(String[] args) {
    System.out.println(10 + 5 * 2); // multiplication is performed before addition, so this will print 20
    System.out.println((10 + 5) * 2); // parentheses change the order of operations, so this will print 30
    System.out.println(10 + 5 * 2 - 3); // multiplication is
}
    

}
